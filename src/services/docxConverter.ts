import { renderAsync } from 'docx-preview';
import html2canvas from 'html2canvas';
import type { PageRenderResult } from './pdfConverter';

export async function convertDocx(
  data: Uint8Array,
  options: {
    scale: number;
    format: 'png' | 'jpg';
    jpegQuality: number;
  },
  onProgress?: (current: number, total: number, previewUrl?: string) => void
): Promise<PageRenderResult[]> {
  // Create offscreen host container attached to DOM for CSS layout calculation
  const host = document.createElement('div');
  host.id = `docx-sandbox-${Date.now()}`;
  host.style.position = 'fixed';
  host.style.left = '0';
  host.style.top = '0';
  host.style.width = '210mm';
  host.style.minHeight = '297mm';
  host.style.opacity = '0';
  host.style.pointerEvents = 'none';
  host.style.zIndex = '-9999';
  host.style.background = '#ffffff';
  host.style.overflow = 'hidden';

  const bodyContainer = document.createElement('div');
  const styleContainer = document.createElement('div');
  host.appendChild(styleContainer);
  host.appendChild(bodyContainer);
  document.body.appendChild(host);

  try {
    // Render DOCX into HTML structure with native page breaks enabled
    await renderAsync(data.buffer as ArrayBuffer, bodyContainer, styleContainer, {
      inWrapper: true,
      ignoreWidth: false,
      ignoreHeight: false,
      breakPages: true,
      experimental: true,
      useBase64URL: true,
      renderChanges: false,
      ignoreLastRenderedPageBreak: false, // Respect Word page breaks
      renderHeaders: true,
      renderFooters: true,
      renderFootnotes: true,
      renderEndnotes: true,
    });

    // Ensure fonts and nested images have finished layout
    if ('fonts' in document) {
      await document.fonts.ready;
    }
    await new Promise((r) => setTimeout(r, 200));

    // Look for section.docx elements generated by docx-preview
    let sectionElements = Array.from(bodyContainer.querySelectorAll<HTMLElement>('section.docx, .docx-wrapper > section'));
    
    if (sectionElements.length === 0) {
      const wrapper = bodyContainer.querySelector<HTMLElement>('.docx-wrapper') || bodyContainer;
      sectionElements = [wrapper];
    }

    // A4 height at 96 DPI is approximately 1123px (297mm)
    const STANDARD_PAGE_HEIGHT_PX = 1123;
    const pageSnapshots: { element: HTMLElement; clipY?: number; clipHeight?: number }[] = [];

    for (const section of sectionElements) {
      const sectionHeight = section.scrollHeight || section.offsetHeight;
      if (sectionHeight > STANDARD_PAGE_HEIGHT_PX * 1.35) {
        // Multi-page flowing section: paginate into distinct separate pages
        const numSubPages = Math.ceil(sectionHeight / STANDARD_PAGE_HEIGHT_PX);
        for (let p = 0; p < numSubPages; p++) {
          pageSnapshots.push({
            element: section,
            clipY: p * STANDARD_PAGE_HEIGHT_PX,
            clipHeight: Math.min(STANDARD_PAGE_HEIGHT_PX, sectionHeight - p * STANDARD_PAGE_HEIGHT_PX),
          });
        }
      } else {
        pageSnapshots.push({ element: section });
      }
    }

    const totalPages = Math.max(1, pageSnapshots.length);
    const results: PageRenderResult[] = [];

    for (let i = 0; i < totalPages; i++) {
      const snapshot = pageSnapshots[i];
      const pageNum = i + 1;

      // Render section to canvas
      const fullCanvas = await html2canvas(snapshot.element, {
        scale: options.scale,
        backgroundColor: '#ffffff',
        useCORS: true,
        logging: false,
        allowTaint: true,
      });

      let finalCanvas = fullCanvas;

      // If sliced from a tall flowing section, extract that specific page slice
      if (snapshot.clipY !== undefined && snapshot.clipHeight !== undefined) {
        finalCanvas = document.createElement('canvas');
        finalCanvas.width = fullCanvas.width;
        finalCanvas.height = Math.round(snapshot.clipHeight * options.scale);
        const ctx = finalCanvas.getContext('2d');
        if (ctx) {
          ctx.fillStyle = '#ffffff';
          ctx.fillRect(0, 0, finalCanvas.width, finalCanvas.height);
          ctx.drawImage(
            fullCanvas,
            0,
            Math.round(snapshot.clipY * options.scale),
            fullCanvas.width,
            finalCanvas.height,
            0,
            0,
            finalCanvas.width,
            finalCanvas.height
          );
        }
      }

      const mimeType = options.format === 'jpg' ? 'image/jpeg' : 'image/png';
      const quality = options.format === 'jpg' ? options.jpegQuality : undefined;

      const blob = await new Promise<Blob>((resolve, reject) => {
        finalCanvas.toBlob(
          (b) => {
            if (b) resolve(b);
            else reject(new Error(`Failed to convert canvas to blob for docx page ${pageNum}`));
          },
          mimeType,
          quality
        );
      });

      const arrayBuffer = await blob.arrayBuffer();
      const imageBytes = new Uint8Array(arrayBuffer);
      const previewDataUrl = finalCanvas.toDataURL('image/jpeg', 0.45);

      results.push({
        pageNumber: pageNum,
        totalPages,
        imageBytes,
        previewDataUrl,
        width: finalCanvas.width,
        height: finalCanvas.height,
      });

      if (onProgress) {
        onProgress(pageNum, totalPages, previewDataUrl);
      }
    }

    return results;
  } finally {
    if (host.parentNode) {
      host.parentNode.removeChild(host);
    }
  }
}
